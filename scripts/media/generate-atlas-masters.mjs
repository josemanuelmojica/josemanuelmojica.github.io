#!/usr/bin/env node
/**
 * generate-atlas-masters.mjs
 *
 * Rasterises the clean map-only SVG masters in
 * `public/maps/national-ink-atlas/masters/` into a responsive WebP/AVIF
 * ladder for the site.
 *
 * Why this exists: the previous site studies were 1200x1600 rasters, and the
 * atlas tile generator sampled those. On a high-DPI desktop the field was
 * being asked for more pixels than the source contained, so it read soft.
 * These masters are true vector (generated from OpenStreetMap via
 * create_map_poster.py --map-only, arx_text_graphite theme), so every rung of
 * the ladder below is genuine detail rather than an upscale.
 *
 * The masters are the archival source and are NOT shipped to the browser;
 * only the derivatives in `renders/` are. The original titled japanese_ink
 * poster SVGs remain untouched under reference/ as print assets.
 *
 * OpenStreetMap attribution is deliberately NOT baked into the artwork — it
 * belongs at the site/component level (see the site footer).
 *
 * Usage:
 *   node scripts/media/generate-atlas-masters.mjs           # generate
 *   node scripts/media/generate-atlas-masters.mjs --check   # verify manifest
 */

import { createHash } from "node:crypto";
import { readdir, readFile, writeFile, mkdir, rm } from "node:fs/promises";
import { existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { execFile } from "node:child_process";
import { promisify } from "node:util";
import sharp from "sharp";

const run = promisify(execFile);

const ROOT = fileURLToPath(new URL("../../", import.meta.url));
/**
 * Masters live OUTSIDE public/. Next copies public/ wholesale into the static
 * export, so masters kept there would ship to every visitor — 13 MB per city,
 * ~100 MB across the eight, for files the browser never requests. They are
 * archival source; only `renders/` is served.
 */
const MASTERS = path.join(ROOT, "assets/national-ink-atlas/masters");
const RENDERS = path.join(ROOT, "public/maps/national-ink-atlas/renders");
const MANIFEST_PATH = path.join(ROOT, "public/maps/national-ink-atlas/atlas-manifest.json");

/**
 * Render ladder. 1024 covers small/standard viewports; 2048 covers standard
 * desktop and high-DPI tablets; 3840 covers large desktop and the long
 * scrolling canvas, where the map is displayed very wide.
 *
 * 5120 is deliberately NOT generated by default: at AVIF it lands in the
 * multi-megabyte range for a decorative field, which no viewport justifies
 * downloading. Pass --with-5k if a specific print/hero use appears.
 */
const WIDTHS = [1024, 2048, 3840];
const EXTRA_WIDTH = 5120;

/** Quality scales down as pixel count climbs, so large rungs stay shippable. */
function qualityFor(width) {
  if (width <= 1024) return { webp: { quality: 80, effort: 6 }, avif: { quality: 55, effort: 4 } };
  if (width <= 2048) return { webp: { quality: 76, effort: 6 }, avif: { quality: 50, effort: 4 } };
  if (width <= 3840) return { webp: { quality: 70, effort: 6 }, avif: { quality: 44, effort: 6 } };
  return { webp: { quality: 64, effort: 6 }, avif: { quality: 38, effort: 6 } };
}

function sha8(buffer) {
  return createHash("sha256").update(buffer).digest("hex").slice(0, 8);
}

async function rasterise(svgPath, width) {
  // rsvg-convert handles these large matplotlib-emitted SVGs reliably and
  // fast; sharp's own SVG input caps out on files this size.
  const tmp = path.join(RENDERS, `.tmp-${path.basename(svgPath, ".svg")}-${width}.png`);
  await run("rsvg-convert", ["-w", String(width), "-o", tmp, svgPath], {
    maxBuffer: 1024 * 1024 * 64,
  });
  const png = await readFile(tmp);
  await rm(tmp, { force: true });
  return png;
}

async function main() {
  const check = process.argv.includes("--check");
  const withExtra = process.argv.includes("--with-5k");
  const widths = withExtra ? [...WIDTHS, EXTRA_WIDTH] : WIDTHS;

  if (!existsSync(MASTERS)) {
    console.error(`No masters directory at ${MASTERS}`);
    process.exit(1);
  }

  const svgs = (await readdir(MASTERS)).filter((f) => f.endsWith(".svg")).sort();
  if (svgs.length === 0) {
    console.error("No SVG masters found.");
    process.exit(1);
  }

  if (check) {
    if (!existsSync(MANIFEST_PATH)) {
      console.error("atlas-manifest.json missing — run without --check first.");
      process.exit(1);
    }
    const manifest = JSON.parse(await readFile(MANIFEST_PATH, "utf8"));
    let missing = 0;
    for (const study of Object.values(manifest.studies)) {
      for (const variant of Object.values(study.renders)) {
        for (const fmt of ["avif", "webp"]) {
          const rel = variant[fmt].path.replace(/^\//, "");
          if (!existsSync(path.join(ROOT, "public", rel))) {
            console.error(`missing ${variant[fmt].path}`);
            missing += 1;
          }
        }
      }
    }
    if (missing > 0) process.exit(1);
    console.log("Atlas master renders verified");
    return;
  }

  await mkdir(RENDERS, { recursive: true });

  const manifest = {
    schemaVersion: 1,
    name: "Arχ & Teχt National Ink Atlas",
    generatedFrom: "scripts/media/generate-atlas-masters.mjs",
    theme: "arx_text_graphite",
    source: {
      dataset: "OpenStreetMap via osmnx",
      attribution: "© OpenStreetMap contributors",
      note: "Attribution is rendered at the site/component level, never baked into the artwork.",
    },
    studies: {},
  };

  for (const svg of svgs) {
    const id = svg.replace(/\.svg$/, "");
    const svgPath = path.join(MASTERS, svg);
    const renders = {};
    for (const width of widths) {
      const png = await rasterise(svgPath, width);
      const base = sharp(png);
      const meta = await base.metadata();
      const q = qualityFor(width);
      const variant = { width, height: meta.height ?? null };
      for (const [format, opts] of [["avif", q.avif], ["webp", q.webp]]) {
        const bytes = await base.clone()[format](opts).toBuffer();
        const name = `${id}-${width}-${sha8(bytes)}.${format}`;
        await writeFile(path.join(RENDERS, name), bytes);
        variant[format] = {
          path: `/maps/national-ink-atlas/renders/${name}`,
          bytes: bytes.length,
        };
      }
      renders[width] = variant;
      console.log(
        `${id} @${width}: avif ${(variant.avif.bytes / 1024).toFixed(0)} KiB, webp ${(variant.webp.bytes / 1024).toFixed(0)} KiB`
      );
    }
    manifest.studies[id] = { id, renders };
  }

  await writeFile(MANIFEST_PATH, `${JSON.stringify(manifest, null, 2)}\n`);
  console.log(`\nWrote ${path.relative(ROOT, MANIFEST_PATH)} (${svgs.length} studies)`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
